-- Initial schema for the prompt gallery. Apply to an empty Supabase project.
-- Import the supplied *_rows.sql files separately; admin credentials are not stored here.
CREATE TABLE public.categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  name_en text,
  prompt_type text NOT NULL DEFAULT 'image' CHECK (prompt_type IN ('image', 'functional')),
  parent_id bigint REFERENCES public.categories(id),
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.tags (
  id text PRIMARY KEY,
  name_zh text NOT NULL,
  name_en text NOT NULL,
  slug text NOT NULL UNIQUE,
  count integer NOT NULL DEFAULT 0 CHECK (count >= 0),
  prompt_type text NOT NULL DEFAULT 'all' CHECK (prompt_type IN ('all', 'image', 'functional'))
);

CREATE TABLE public.prompts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  title_en text,
  preview text,
  prompt text NOT NULL,
  prompt_en text,
  author text NOT NULL,
  link text,
  mode text NOT NULL DEFAULT 'generate' CHECK (mode IN ('generate', 'edit')),
  category text NOT NULL,
  sub_category text,
  tags text[],
  created_at timestamptz NOT NULL DEFAULT now(),
  prompt_type text NOT NULL DEFAULT 'image' CHECK (prompt_type IN ('image', 'functional')),
  description text,
  description_en text,
  use_cases text[],
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.admin_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX categories_parent_id_idx ON public.categories(parent_id);
CREATE INDEX prompts_type_created_at_idx ON public.prompts(prompt_type, created_at DESC);
CREATE INDEX prompts_created_at_idx ON public.prompts(created_at DESC);
CREATE INDEX prompts_category_idx ON public.prompts(category);
CREATE INDEX prompts_tags_idx ON public.prompts USING gin(tags);

ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tags ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.prompts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_users ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.categories, public.tags, public.prompts, public.admin_users FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
-- All reads go through the server; anonymous reads bypass its rate limiter.
GRANT ALL ON TABLE public.categories, public.tags, public.prompts, public.admin_users TO service_role;
REVOKE ALL ON SEQUENCE public.categories_id_seq, public.prompts_id_seq, public.admin_users_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.categories_id_seq, public.prompts_id_seq, public.admin_users_id_seq TO service_role;

NOTIFY pgrst, 'reload schema';
